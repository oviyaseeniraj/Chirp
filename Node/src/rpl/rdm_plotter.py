def create_rdm_animation(frames_data, output_path, fps=5):
    """Create an animation of RDM frames.

    Args:
        frames_data: List of (rdm_data, metadata) tuples
        output_path: Path to save the animation (MP4 or GIF)
        fps: Frames per second
    """
    if not frames_data:
        print("No frames to animate")
        return

    fig, ax = plt.subplots(figsize=(12, 8))

    # Initialize with first frame
    rdm_data, metadata = frames_data[0]
    rdm_display = rdm_data[:, : FAST_TIME // 2].T
    range_axis, velocity_axis = compute_axes(rdm_data.shape)
    extent = [velocity_axis[0], velocity_axis[-1], 0, range_axis[-1]]

    im = ax.imshow(
        rdm_display,
        aspect="auto",
        origin="lower",
        extent=extent,
        cmap="jet",
        interpolation="nearest",
        animated=True,
    )
    plt.colorbar(im, ax=ax, label="Magnitude (dB)")

    (detection_marker,) = ax.plot([], [], "wx", markersize=15, mew=3)

    ax.set_xlabel("Velocity (m/s)", fontsize=12)
    ax.set_ylabel("Range (m)", fontsize=12)
    title = ax.set_title("", fontsize=14)
    ax.grid(True, alpha=0.3, linestyle="--")
    ax.axvline(x=0, color="white", linestyle="--", alpha=0.5)

    def update(frame_idx):
        rdm_data, metadata = frames_data[frame_idx]
        rdm_display = rdm_data[:, : FAST_TIME // 2].T
        im.set_array(rdm_display)

        # Update detection marker
        if "Range" in metadata and "Doppler" in metadata:
            detection_marker.set_data([metadata["Doppler"]], [metadata["Range"]])

        # Update title
        node = metadata.get("Node", "Unknown")
        frame = metadata.get("Frame Number", frame_idx)
        title.set_text(f"Range-Doppler Map - {node} Frame {frame}")

        return [im, detection_marker, title]

    anim = animation.FuncAnimation(
        fig, update, frames=len(frames_data), interval=1000 / fps, blit=True
    )

    # Save animation
    if output_path.endswith(".gif"):
        anim.save(output_path, writer="pillow", fps=fps)
    else:
        anim.save(output_path, writer="ffmpeg", fps=fps)

    plt.close()
    print(f"Saved animation: {output_path}")


