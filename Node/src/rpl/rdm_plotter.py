# Radar parameters (must match implementation.cpp)
FAST_TIME = 512  # Number of range bins
SLOW_TIME = 64  # Number of doppler bins
CARRIER_FREQ = 77e9  # 77 GHz carrier frequency
SPEED_OF_LIGHT = 3e8
LAMBDA = SPEED_OF_LIGHT / CARRIER_FREQ  # ~0.0039m wavelength
CHIRP_DURATION = 100e-6  # 100 microseconds
MAX_VELOCITY = LAMBDA / (4.0 * CHIRP_DURATION)  # Maximum unambiguous velocity
VELOCITY_RES = 2.0 * MAX_VELOCITY / SLOW_TIME  # Velocity resolution per bin

# Range parameters (from implementation.cpp)
RANGE_MULTIPLIER = 9.0 / 256.0  # meters per bin (for half of FAST_TIME)
MAX_RANGE = 9.0  # Maximum range in meters


def load_rdm_binary(filepath):
    """Load binary RDM data file generated by C++.

    File format:
    - 2 integers: [SLOW_TIME, FAST_TIME] (dimensions)
    - SLOW_TIME * FAST_TIME floats: RDM data (already fftshifted)

    Args:
        filepath: Path to the .bin file

    Returns:
        2D numpy array of shape (SLOW_TIME, FAST_TIME)
    """
    with open(filepath, "rb") as f:
        # Read dimensions
        dims = np.fromfile(f, dtype=np.int32, count=2)
        slow_time, fast_time = dims[0], dims[1]

        # Read RDM data
        rdm_data = np.fromfile(f, dtype=np.float32, count=slow_time * fast_time)
        rdm_data = rdm_data.reshape((slow_time, fast_time))

    return rdm_data


def load_json_metadata(filepath):
    """Load JSON metadata for a frame.

    Args:
        filepath: Path to the .json file

    Returns:
        Dictionary with frame metadata
    """
    with open(filepath, "r") as f:
        return json.load(f)


def find_frame_files(data_dir, node_name=None):
    """Find all frame files in the data directory.

    Args:
        data_dir: Directory containing frame data
        node_name: Optional filter by node name

    Returns:
        List of tuples: (json_path, rdm_path, frame_num)
    """
    json_files = glob.glob(os.path.join(data_dir, "*_Frame*.json"))

    frames = []
    for json_path in json_files:
        # Extract frame number from filename
        basename = os.path.basename(json_path)
        try:
            parts = basename.replace(".json", "").split("_Frame")
            name = parts[0]
            frame_num = int(parts[1])
        except (IndexError, ValueError):
            continue

        # Check node name filter
        if node_name and name != node_name:
            continue

        # Check for corresponding RDM file
        rdm_path = json_path.replace(".json", "_rdm.bin")
        if os.path.exists(rdm_path):
            frames.append((json_path, rdm_path, frame_num))

    # Sort by frame number
    frames.sort(key=lambda x: x[2])
    return frames


def compute_axes(rdm_shape):
    """Compute range and velocity axes for plotting.

    Args:
        rdm_shape: Tuple of (slow_time, fast_time)

    Returns:
        range_axis: 1D array of range values in meters
        velocity_axis: 1D array of velocity values in m/s
    """
    slow_time, fast_time = rdm_shape

    # Range axis (only using first half due to fftshift behavior)
    # Range bins go from 0 to max_range
    range_axis = np.linspace(0, MAX_RANGE, fast_time // 2)

    # Velocity axis (centered at 0 after fftshift)
    # Bins are: [-max_vel, ..., 0, ..., +max_vel]
    velocity_axis = np.linspace(-MAX_VELOCITY, MAX_VELOCITY, slow_time)

    return range_axis, velocity_axis


def plot_rdm_single(rdm_data, metadata, output_path, show_detection=True):
    """Plot a single range-doppler map.

    Args:
        rdm_data: 2D numpy array of RDM data
        metadata: Dictionary with frame metadata
        output_path: Path to save the plot
        show_detection: Whether to highlight the detection point
    """
    fig, ax = plt.subplots(figsize=(12, 8))

    # Only show the relevant portion (first half of range)
    # Data is already fftshifted in doppler dimension
    rdm_display = rdm_data[:, : FAST_TIME // 2].T  # Transpose so range is Y-axis

    # Compute axes
    range_axis, velocity_axis = compute_axes(rdm_data.shape)

    # Create the heatmap
    extent = [velocity_axis[0], velocity_axis[-1], 0, range_axis[-1]]
    im = ax.imshow(
        rdm_display,
        aspect="auto",
        origin="lower",
        extent=extent,
        cmap="jet",
        interpolation="nearest",
    )

    # Add colorbar
    cbar = plt.colorbar(im, ax=ax, label="Magnitude (dB)")

    # Mark detection point if available
    if show_detection and "Range" in metadata and "Doppler" in metadata:
        detected_range = metadata["Range"]
        detected_doppler = metadata["Doppler"]
        ax.scatter(
            [detected_doppler],
            [detected_range],
            marker="x",
            s=200,
            c="white",
            linewidths=3,
            label=f"Detection: R={detected_range:.2f}m, V={detected_doppler:.2f}m/s",
        )
        ax.legend(loc="upper right", fontsize=10)

    # Labels and title
    ax.set_xlabel("Velocity (m/s)", fontsize=12)
    ax.set_ylabel("Range (m)", fontsize=12)

    node = metadata.get("Node", "Unknown")
    frame = metadata.get("Frame Number", 0)
    angle = metadata.get("Angle", 0)
    elapsed = metadata.get("Elapsed Time (ms)", 0)

    title = f"Range-Doppler Map - {node} Frame {frame}\n"
    title += f"Angle: {angle:.1f}°, Elapsed: {elapsed}ms"
    ax.set_title(title, fontsize=14)

    # Add grid
    ax.grid(True, alpha=0.3, linestyle="--")

    # Add zero-velocity line
    ax.axvline(x=0, color="white", linestyle="--", alpha=0.5, linewidth=1)

    plt.tight_layout()
    plt.savefig(output_path, dpi=150, bbox_inches="tight")
    plt.close()

    print(f"Saved: {output_path}")


